"""Build binary resources, WeiDU stamp installer TPA, and TRA texts from defs/*.json."""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from resformat import StampRef, pack_eff, pack_itm, pack_spl  # noqa: E402

DEFS_DIR = ROOT / "defs"
RES_DIR = ROOT / "chriz-bg-kits" / "res"
LIB_OUT = ROOT / "chriz-bg-kits" / "lib" / "cbk_resources.tpa"
TRA_OUT = ROOT / "chriz-bg-kits" / "languages" / "english" / "resources.tra"


def render_outputs() -> dict[pathlib.Path, bytes]:
    outputs: dict[pathlib.Path, bytes] = {}
    all_stamps: list[StampRef] = []
    texts: dict[str, str] = {}
    splprots: dict[str, dict[str, int]] = {}
    states: set[str] = set()
    res_groups: dict[str, list[str]] = defaultdict(list)

    for def_path in sorted(DEFS_DIR.glob("*.json")):
        group_name = def_path.stem
        spec = json.loads(def_path.read_text(encoding="utf-8"))
        for key, txt in spec.get("texts", {}).items():
            if key in texts and texts[key] != txt:
                raise ValueError(f"Conflicting text key {key!r}")
            texts[key] = txt
        for sym, row in spec.get("splprots", {}).items():
            if sym in splprots and splprots[sym] != row:
                raise ValueError(f"Conflicting splprot key {sym!r}")
            splprots[sym] = {
                "stat": row["stat"],
                "value": row["value"],
                "relation": row["relation"],
            }
        for sym in spec.get("states", []):
            states.add(sym)

        for res_spec in spec.get("resources", []):
            filename = res_spec["file"].upper()
            res_groups[group_name].append(filename)
            ext = pathlib.Path(filename).suffix.upper()
            if ext == ".SPL":
                blob, stamps = pack_spl(res_spec, filename)
            elif ext == ".EFF":
                blob, stamps = pack_eff(res_spec, filename)
            elif ext == ".ITM":
                blob, stamps = pack_itm(res_spec, filename)
            else:
                raise ValueError(f"Unsupported resource extension in {def_path.name}: {filename}")
            all_stamps.extend(stamps)
            for s in stamps:
                if s.kind == "state":
                    states.add(s.symbol)
            outputs[RES_DIR / filename] = blob

    # Generate TRA for symbolic resource texts (@90000+)
    tra_lines = ["// Generated by tools/build_resources.py — do not edit manually.", ""]
    text_ids: dict[str, int] = {}
    for idx, (key, val) in enumerate(sorted(texts.items()), start=90000):
        text_ids[key] = idx
        escaped = val.replace("~", "\"")
        tra_lines.append(f"@{idx} = ~{escaped}~")
    outputs[TRA_OUT] = ("\n".join(tra_lines) + "\n").encode("utf-8")

    # Group stamps by file
    stamps_by_file: dict[str, list[StampRef]] = defaultdict(list)
    for st in all_stamps:
        stamps_by_file[st.file].append(st)

    # Generate WeiDU helper cbk_resources.tpa
    ret_vars = [f"cbk_state_{sym}" for sym in sorted(states)] + [
        f"cbk_splprot_{sym}" for sym in sorted(splprots.keys())
    ]
    tpa = [
        "// Generated by tools/build_resources.py — do not edit manually.",
        "",
        "DEFINE_ACTION_FUNCTION cbk_ensure_resource_symbols",
        "  RET " + " ".join(ret_vars),
        "BEGIN",
    ]
    for sym in sorted(states):
        tpa.append(f"  LAF cbk_ensure_splstate STR_VAR symbol = ~{sym}~ RET cbk_state_{sym} = state END")
    for sym, row in sorted(splprots.items()):
        stat_expr = repr_stat(row["stat"])
        val_expr = repr_val(row["value"])
        tpa.append(
            f"  LAF cbk_ensure_splprot STR_VAR label = ~{sym}~ stat = ~{stat_expr}~ "
            f"value = EVAL ~{val_expr}~ relation = ~{row['relation']}~ RET cbk_splprot_{sym} = row END"
        )
    tpa.append("END")
    tpa.append("")

    for group_name, files in sorted(res_groups.items()):
        tpa.append(f"DEFINE_ACTION_FUNCTION cbk_install_res_{group_name} BEGIN")
        tpa.append("  LAF cbk_ensure_resource_symbols RET " + " ".join(ret_vars) + " END")
        for fn in files:
            tpa.append(f"  COPY ~%MOD_FOLDER%/res/{fn}~ ~override/{fn}~")
            for st in stamps_by_file.get(fn, []):
                writer = {1: "WRITE_BYTE", 2: "WRITE_SHORT", 4: "WRITE_LONG"}[st.size]
                if st.kind == "text":
                    tid = text_ids[st.symbol]
                    tpa.append(f"    SAY {hex(st.offset)} @{tid}")
                elif st.kind == "state":
                    tpa.append(f"    {writer} {hex(st.offset)} cbk_state_{st.symbol}")
                elif st.kind == "splprot":
                    tpa.append(f"    {writer} {hex(st.offset)} cbk_splprot_{st.symbol}")
                elif st.kind == "stat":
                    tpa.append(f"    SET _cbk_st = IDS_OF_SYMBOL (~stats~ ~{st.symbol}~)")
                    tpa.append(f"    {writer} {hex(st.offset)} _cbk_st")
                elif st.kind == "proj":
                    tpa.append(f"    SET _cbk_pj = IDS_OF_SYMBOL (~projectl~ ~{st.symbol}~)")
                    tpa.append(f"    PATCH_IF (_cbk_pj >= 0) BEGIN {writer} {hex(st.offset)} (_cbk_pj + 1) END")
                else:
                    raise ValueError(f"Unsupported stamp kind: {st.kind}")
        tpa.append("END")
        tpa.append("")

    outputs[LIB_OUT] = ("\n".join(tpa) + "\n").encode("utf-8")
    return outputs


def repr_stat(stat: int | str) -> str:
    if isinstance(stat, int):
        return str(stat)
    return str(stat)


def repr_val(val: int | str) -> str:
    if isinstance(val, str) and val.startswith("STATE:"):
        sym = val.split(":", 1)[1]
        return f"%cbk_state_{sym}%"
    return str(val)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify generated outputs match disk byte-for-byte.")
    args = parser.parse_args()

    expected = render_outputs()
    if args.check:
        drift = []
        for path, data in sorted(expected.items()):
            if not path.exists() or path.read_bytes() != data:
                drift.append(str(path.relative_to(ROOT)))
        existing_res = set(RES_DIR.glob("*")) if RES_DIR.exists() else set()
        extra = [str(p.relative_to(ROOT)) for p in sorted(existing_res) if p not in expected]
        if drift or extra:
            print("RESOURCE DRIFT:", {"drift": drift, "extra": extra})
            return 1
        print(f"build_resources --check OK ({len(expected)} files exact)")
        return 0

    RES_DIR.mkdir(parents=True, exist_ok=True)
    for p in list(RES_DIR.glob("*")):
        if p not in expected:
            p.unlink()
    for path, data in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"Generated {len(expected)} resource and installer files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
